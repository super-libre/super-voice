"""Small-size versions of the Super Voice icon, built from the real layers.

Both glyphs are made from the same geometry as the master: the layer SVGs in
.claude/skills/super-voice-icon/layers/. Nothing is redrawn by hand, so the
small icon and the 256 px icon are the same picture.

small_svg(n, tile)  the colour icon for 16-32 px. The ground, glass bands,
                    light, ink shadow and S roundel are the real layers. The
                    cape and the mic are the real outlines with the fine
                    detail (halftone mesh, hatching, stripes, LED) replaced by
                    flat tones of the same average colour, and a heavier ink
                    outline sized in pixels, so it survives at 16 px. The ink
                    group is nudged by under half a pixel so the roundel's
                    centre lands on a pixel centre.

tray_svg(n, color)  the one-colour notification-area glyph: the same mic,
                    knobs and cape as a solid silhouette, with the seam and the
                    cape/mic boundary as 1 px gaps, and the S roundel cut out
                    (24 and 32 px) or a round hole (16 and 20 px).
"""
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", "..", ".."))
LAYERS = os.path.join(REPO, ".claude", "skills", "super-voice-icon", "layers")

# The ink group's frame, from mic.svg / cape-00.svg / emblem.svg:
#   rotate(5 238 290) translate(238 290) rotate(40) scale(1.3216)
# which is world = (238, 290) + 1.3216 * R(45 deg) * local.
INK_FRAME = '<g transform="rotate(5 238 290)"><g transform="translate(238 290) rotate(40) scale(1.3216)">'
INK_END = "</g></g>"
SCALE = 1.3216
ROUNDEL_LOCAL = (0.0, 66.0)

INK = "#171614"
CAPSULE = "M-63 -87A63 63 0 0 1 63 -87V130Q63 150 43 150H-43Q-63 150 -63 130Z"
DOME = "M-63 -12V-87A63 63 0 0 1 63 -87V-12Z"
HOUSING = "M-63 0H63V130Q63 150 43 150H-43Q-63 150 -63 130Z"
KNOBS = [
    "M-63 4H-80Q-87 4 -87 11V39Q-87 46 -80 46H-63Z",
    "M63 4H80Q87 4 87 11V39Q87 46 80 46H63Z",
    "M63 86H73Q80 86 80 93V121Q80 128 73 128H63Z",
]
SEAM = "M-66 -14H66V2H-66Z"


def _read(name):
    return open(os.path.join(LAYERS, name)).read()


def _inner(svg):
    """The children of a layer's root <svg>."""
    return svg[svg.index(">", svg.index("<svg")) + 1 : svg.rindex("</svg>")]


def _nested(name, box):
    x, y, w, h = box
    return (
        f'<svg x="{x}" y="{y}" width="{w}" height="{h}" viewBox="{x} {y} {w} {h}" overflow="visible">'
        f"{_inner(_read(name))}</svg>"
    )


CAPE_D = re.search(r'<path d="([^"]+)" fill="url\(#dskcape0-cape\)"', _read("cape/cape-00.svg")).group(1)
_EMBLEM_PATHS = re.findall(r'<path d="([^"]*)"', _read("emblem.svg"))
ROUNDEL_OUTER = _EMBLEM_PATHS[1]  # the roundel's outer ink edge
ROUNDEL_CORAL = _EMBLEM_PATHS[7]  # the coral disc
S_OUTLINE = _EMBLEM_PATHS[10]  # the S with its ink outline
S_FILL = _EMBLEM_PATHS[14]  # the S's yellow face


def world(local):
    x, y = local
    c = s = math.sqrt(0.5)
    return 238 + SCALE * (x * c - y * s), 290 + SCALE * (x * s + y * c)


def _units_per_px(tile):
    """Local ink-frame units per output pixel, for a tile drawn at `tile` px."""
    return 512 / tile / SCALE


def _snap_offset(n, tile, pad):
    """World-unit shift that puts the roundel centre on a pixel centre."""
    wx, wy = world(ROUNDEL_LOCAL)
    k = tile / 512
    out = []
    for w in (wx, wy):
        p = pad + w * k
        target = math.floor(p) + 0.5
        out.append((target - p) / k)
    return out


def small_svg(n, tile, pad):
    u = _units_per_px(tile)
    # Ink weight in pixels: heavier than the master's (about 0.7 px at 16 px)
    # so the outline survives. The master uses 18 units.
    ink_px = {16: 1.15, 20: 1.2, 24: 1.3, 30: 1.45, 32: 1.5}.get(n, 1.5)
    w = ink_px * u
    dx, dy = _snap_offset(n, tile, pad)
    highlight = (
        '<ellipse cx="-30" cy="-118" rx="9" ry="16" transform="rotate(35 -30 -118)" fill="#fff" fill-opacity=".95"/>'
        if n >= 24
        else ""
    )
    knobs = "".join(
        f'<path d="{d}" fill="#2b2925" stroke="{INK}" stroke-width="{w*0.8:.1f}" stroke-linejoin="round"/>' for d in KNOBS
    )
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
<!-- Generated by brand/icon/windows/src/glyphs.py for {n} px. Do not edit by hand. -->
<defs>
  <clipPath id="sv-tile"><rect width="512" height="512" rx="112"/></clipPath>
  <linearGradient id="sv-cape" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#ddd34a"/><stop offset="1" stop-color="#a39a1a"/></linearGradient>
  <linearGradient id="sv-hous" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#a9a396"/><stop offset=".42" stop-color="#7c766a"/><stop offset="1" stop-color="#2c2925"/></linearGradient>
  <linearGradient id="sv-dome" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="#ece3cd"/><stop offset=".5" stop-color="#cdc3a9"/><stop offset="1" stop-color="#857d6a"/></linearGradient>
</defs>
<g clip-path="url(#sv-tile)">
  {_nested("ground.svg", (0, 0, 512, 512))}
  {_nested("band-far.svg", (-512, -512, 1536, 1536))}
  {_nested("band-near.svg", (-512, -512, 1536, 1536))}
  {_nested("light.svg", (0, 0, 512, 512))}
  <g transform="translate({dx:.2f} {dy:.2f})">
    {_nested("shadow/shadow-00.svg", (0, 0, 512, 512))}
    {INK_FRAME}
      <path d="{CAPE_D}" fill="url(#sv-cape)" stroke="{INK}" stroke-width="{w:.1f}" stroke-linejoin="round"/>
      {knobs}
      <path d="{HOUSING}" fill="url(#sv-hous)"/>
      <path d="M-42 14V136" stroke="#fff" stroke-opacity=".45" stroke-width="10" stroke-linecap="round"/>
      <path d="{DOME}" fill="url(#sv-dome)"/>
      {highlight}
      <path d="{CAPSULE}" fill="none" stroke="{INK}" stroke-width="{w:.1f}" stroke-linejoin="round"/>
      <path d="{SEAM}" fill="#2b2925" stroke="{INK}" stroke-width="{w*0.6:.1f}" stroke-linejoin="round"/>
    {INK_END}
    {_nested("emblem.svg", (0, 0, 512, 512))}
  </g>
</g>
</svg>"""


# The tray glyph is the mic and a short cape: the cape is cut off square to
# the flight line (x - y = CAPE_CUT) and the view is fitted around the result.
CAPE_CUT = -430
TRAY_VIEW = (-93, -3, 530, 530)


# Sub-pixel shifts (in px) per size that make the 45-degree edges crispest:
# found by rendering every 1/8 px shift and keeping the one with the fewest
# half-covered pixels (`python3 build.py --tune-tray` prints them again).
TRAY_SHIFT = {16: (0.125, 0.25), 20: (0.0, 0.5), 24: (0.125, 0.0), 32: (0.125, 0.125)}


def tray_svg(n, color, shift=None):
    """The tray glyph: the same small icon as the macOS menu bar, drawn by
    menubar_svg in brand/icon/macos/tools/build.py and cut for n px at 1x,
    in the taskbar's colour. `shift` is kept for build.py's --tune-tray and
    ignored: menubar_svg already fits the glyph to the pixel grid."""
    import importlib.util, os as _os
    here = _os.path.dirname(_os.path.abspath(__file__))
    mac_build = _os.path.join(here, "..", "..", "macos", "tools", "build.py")
    spec = importlib.util.spec_from_file_location("sv_macos_build", mac_build)
    mac = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mac)
    return mac.menubar_svg(n, 1).replace('fill="#000"', f'fill="{color}"')

